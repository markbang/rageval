def load_csv_rows(path: Path) -> list[dict[str, str]]:
    if not path.exists():
        raise FileNotFoundError(f"Required CSV not found: {path}")
    with path.open("r", encoding="utf-8-sig", newline="") as handle:
        return [{key: value or "" for key, value in row.items()} for row in csv.DictReader(handle)]


def safe_float(value: str | float | int | None) -> float | None:
    if value in (None, ""):
        return None
    try:
        parsed = float(value)
    except ValueError:
        return None
    if isnan(parsed):
        return None
    return parsed


def safe_int(value: str | int | None) -> int:
    try:
        return int(str(value or "0"))
    except ValueError:
        return 0


def mean_or_none(values: list[float]) -> float | None:
    return None if not values else statistics.fmean(values)


def std_or_none(values: list[float]) -> float | None:
    if len(values) < 2:
        return None
    return statistics.stdev(values)


def flatten_doc_rows(doc_summary_rows: list[dict[str, str]]) -> list[dict[str, Any]]:
    numeric_fields = [
        "exact_match",
        "token_f1_score",
        "numeric_tolerance_score",
        "semantic_similarity",
        "answer_accuracy",
        "faithfulness",
        "response_relevancy",
        "context_precision",
        "context_recall",
        "context_entity_recall",
        "context_pr_f1",
        "reference_alignment_score",
        "answer_quality_score",
        "retrieval_quality_score",
        "overall_quality_score",
    ]
    rows: list[dict[str, Any]] = []
    for row in doc_summary_rows:
        item: dict[str, Any] = {
            "system": row.get("system", ""),
            "dataset_name": row.get("dataset_name", ""),
            "doc_id": row.get("doc_id", ""),
            "evaluation_set": row.get("evaluation_set", ""),
            "length_bucket": row.get("length_bucket", ""),
            "row_count": safe_int(row.get("row_count")),
            "error_row_count": safe_int(row.get("error_row_count")),
            "numeric_question_count": safe_int(row.get("numeric_question_count")),
            "avg_error_question_rate": 0.0,
            "avg_numeric_question_share": 0.0,
        }
        if item["row_count"] > 0:
            item["avg_error_question_rate"] = item["error_row_count"] / item["row_count"]
            item["avg_numeric_question_share"] = (
                item["numeric_question_count"] / item["row_count"]
            )
        for field in numeric_fields:
            item[field] = safe_float(row.get(field))
        rows.append(item)
    return rows


