def plot_diff_heatmap(
    diff_rows: list[dict[str, Any]],
    path: Path,
) -> None:
    datasets = sorted({row["dataset_name"] for row in diff_rows})
    if not datasets:
        return

    matrix: list[list[float]] = []
    for dataset_name in datasets:
        row_values = []
        for bucket in MAIN_LENGTH_BUCKETS:
            value = next(
                (
                    item["mean_diff_lightrag_minus_vector"]
                    for item in diff_rows
                    if item["dataset_name"] == dataset_name and item["length_bucket"] == bucket
                ),
                0.0,
            )
            row_values.append(value or 0.0)
        matrix.append(row_values)

    plt.figure(figsize=(8, max(4, len(datasets) * 0.6)))
    im = plt.imshow(matrix, cmap="RdBu_r", aspect="auto")
    plt.colorbar(im, label="LightRAG - VectorRAG")
    plt.xticks(range(len(MAIN_LENGTH_BUCKETS)), MAIN_LENGTH_BUCKETS)
    plt.yticks(range(len(datasets)), datasets)
    plt.title("Mean Paired Difference by Dataset and Length Bucket")

    for y, dataset_name in enumerate(datasets):
        for x, bucket in enumerate(MAIN_LENGTH_BUCKETS):
            value = matrix[y][x]
            plt.text(x, y, f"{value:.3f}", ha="center", va="center", fontsize=9)

    ensure_parent_dir(path)
    plt.tight_layout()
    plt.savefig(path, dpi=200)
    plt.close()


